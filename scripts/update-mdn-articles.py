#!/usr/bin/env python3
"""Refresh the bundled MDN articles in js/articles.js for Page Viewer.

The articles are embedded in the app itself, so the Reference panel works
with no network at all (the deploy target only accepts a single file).

Usage:  python scripts/update-mdn-articles.py
Source: mdn/content repo — files/en-us/<slug>/index.md, fetched via
        cdn.jsdelivr.net with raw.githubusercontent.com as fallback.
Output: js/articles.js — 'use strict'; const MDN_ARTICLES = { <flat-slug>: markdown, ... }
        (slug '/' flattened to '--', same mapping the app uses)
"""

import json
import re
import sys
import urllib.request

DATA_JS = "js/data.js"
OUT = "js/articles.js"
UA = {"User-Agent": "Mozilla/5.0 (Page Viewer article updater)"}
BASES = [
    "https://cdn.jsdelivr.net/gh/mdn/content@main/files/en-us/",
    "https://raw.githubusercontent.com/mdn/content/main/files/en-us/",
]


def element_keys():
    src = open(DATA_JS, encoding="utf-8").read()
    block = re.search(r"const ELEMENT_INFO = \{([\s\S]*?)\n\};", src).group(1)
    keys = {k.lower() for k in re.findall(r"^  ([a-z0-9]+):", block, re.M) if k != "doctype"}
    keys.add("heading_elements")            # h1-h6 share one page
    return sorted(keys)


def slug_for(key):
    if re.fullmatch(r"h[1-6]", key):
        return "web/html/reference/elements/heading_elements"
    return "web/html/reference/elements/" + key


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=30) as r:
        return r.read().decode("utf-8")


def main():
    slugs = list(dict.fromkeys(
        [slug_for(k) for k in sorted(element_keys())]
        + ["glossary/doctype", "glossary/character_reference"]
    ))
    articles = {}
    missing = []
    for slug in slugs:
        flat = slug.replace("/", "--")
        md = None
        for base in BASES:
            try:
                md = fetch(base + slug + "/index.md")
                break
            except Exception:
                continue
        if md is None:
            missing.append(slug)
            continue
        articles[flat] = md
        print(f"ok  {slug}  ({len(md)} bytes)")

    body = ",\n".join(f"  {json.dumps(flat)}: {json.dumps(md)}"
                      for flat, md in sorted(articles.items()))
    js = ("'use strict';\n\n"
          "/* GENERATED by scripts/update-mdn-articles.py — bundled MDN articles\n"
          "   (raw Markdown from the mdn/content repo). Regenerate with:\n"
          "   python scripts/update-mdn-articles.py */\n"
          "const MDN_ARTICLES = {\n" + body + "\n};\n")
    open(OUT, "w", encoding="utf-8", newline="\n").write(js)
    print(f"wrote {OUT}: {len(articles)} articles, {missing or 'none'} unavailable")
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
